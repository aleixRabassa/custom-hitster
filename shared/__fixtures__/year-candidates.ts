/**
 * Normalized MusicBrainz candidates for the Phase 0 known-tricky tracks.
 *
 * These are `RecordingCandidate[]` -- the shape `pickBestRecording()` consumes -- not raw
 * MusicBrainz JSON. They live under `shared/` rather than `api/_lib/__fixtures__/` for a
 * boundary reason, not a stylistic one: `tsconfig.app.json` covers `src` + `shared` only,
 * so a `shared/` test importing from `api/` would drag Node-side code into the browser
 * typecheck.
 *
 * The RAW payloads live in `api/_lib/__fixtures__/musicbrainz-payloads.ts` and pin the JSON
 * shape the adapter parses. The two files are captured the same way, on the same date, with
 * the same two queries, and `api/_lib/musicbrainz.test.ts` runs the adapter end to end over
 * its raw fixture and asserts the resulting year — so a shape change breaks that test rather
 * than silently producing candidates this file's scoring tests would never see.
 *
 * ## Why these tracks
 *
 * Phase 0 measured a naive top-scored lookup at ~6% accurate (1 of 18) and established
 * ground-truth years for the cases that broke it. This is that list: compilation-era tracks
 * whose reissues outrank the original, tracks with a famous live version, a cover-versus-
 * original pair, and the two tracks decision 20 flagged as never re-verified (Free Bird and
 * Like a Rolling Stone -- both now confirmed correct).
 *
 * `expectedYear` is the KNOWN-CORRECT original release year, from Phase 0's ground truth --
 * not whatever the code happens to produce. A failure here is a regression in scoring.
 *
 * ## Provenance
 *
 * Captured 2026-08-04 from `musicbrainz.org/ws/2` with
 * `User-Agent: custom-hitster/0.1.0 ( … )`, paced at 1 req/s, using exactly the two
 * requests the adapter makes:
 *
 * ```
 * GET /ws/2/recording?query=recording:"<title>" AND artist:"<artist>"
 *                            AND dur:[<durationMs-10000> TO <durationMs+10000>]&fmt=json&limit=100
 * GET /ws/2/release-group?query=rgid:(<id> OR <id> OR …)&fmt=json&limit=100
 * ```
 *
 * `durationMs` is the real Spotify track duration, which is what makes the `dur:` bound
 * reproducible.
 *
 * **Trimmed, not verbatim.** A capture runs to 200-460 candidates per track, which is
 * unreadable and undiffable. Each entry here keeps one representative candidate per
 * strict-eligible release group, plus up to five excluded candidates chosen to cover
 * distinct exclusion reasons (a Live or Compilation secondary type, a Promotion / Bootleg /
 * Withdrawn status, a Single primary type, an undated release group). Nothing was
 * hand-written or invented. The trimming was verified not to change any answer: for all
 * fourteen tracks, `pickBestRecording()` returns the same year over the trimmed set as over
 * the full capture.
 *
 * `poolSize` records how many recordings the search reported in total, as evidence for the
 * `dur:` bound's effect -- "Stairway to Heaven" is 842 candidates unbounded and 31 bounded,
 * and that difference is why it resolves correctly (docs/agent_findings.md, 2026-08-04).
 */


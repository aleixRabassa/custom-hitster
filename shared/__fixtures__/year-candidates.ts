/**
 * Normalized MusicBrainz candidates for the known-tricky tracks.
 *
 * These are `RecordingCandidate[]` -- the shape `pickBestRecording()` consumes -- not raw
 * MusicBrainz JSON. They live under `shared/` rather than `api/_lib/__fixtures__/` for a
 * boundary reason, not a stylistic one: `tsconfig.app.json` covers `src` + `shared` only,
 * so a `shared/` test importing from `api/` would drag Node-side code into the browser
 * typecheck.
 *
 * The RAW payloads live in `api/_lib/__fixtures__/musicbrainz-payloads.ts` and pin the JSON
 * shape the adapter parses. `api/_lib/musicbrainz.test.ts` runs the adapter end to end over
 * its raw fixture and asserts the resulting year -- so a shape change breaks that test rather
 * than silently producing candidates this file's scoring tests would never see.
 *
 * ## Why these tracks
 *
 * Two groups, captured two years apart in project time and testing two different failures.
 *
 * **The Phase 0 fourteen** (Billie Jean through Smells Like Teen Spirit). Phase 0 measured a
 * naive top-scored lookup at ~6% accurate (1 of 18) and established ground-truth years for the
 * cases that broke it: compilation-era tracks whose reissues outrank the original, tracks with
 * a famous live version, a cover-versus-original pair.
 *
 * **The single-before-album seven** (Creep through Hey Jude), added 2026-08-11. Every one was
 * first issued as a single at least a year before the album that later carried it, which is the
 * shape the pipeline got WRONG until Singles and EPs became eligible for the top scoring rung:
 * a release group's `first-release-date` is the ALBUM's date, so an Album-only filter reports
 * the year the track was included on a record rather than the year the song came out. Hey Jude
 * is the extreme case -- never on a UK studio album at all, so under the old filter it had no
 * eligible release group whatsoever and fell to the unfiltered tier.
 *
 * `expectedYear` is the KNOWN-CORRECT original release year -- ground truth, not whatever the
 * code happens to produce. A failure here is a regression in scoring.
 *
 * ## Provenance
 *
 * The Phase 0 fourteen were first captured 2026-08-04. **All twenty-two entries in this file
 * were RE-captured 2026-08-11** against the live database, because the 2026-08-11 change moved
 * which release groups the adapter's second request asks about: the old captures carried Single
 * candidates with no `releaseGroupFirstReleaseDate`, since nothing had ever fetched one. A
 * fixture that cannot represent the new evidence cannot catch a regression in it.
 *
 * Captured from `musicbrainz.org/ws/2` with `User-Agent: custom-hitster/0.1.0 ( … )`, paced at
 * 1 req/s, using exactly the two requests the adapter makes:
 *
 * ```
 * GET /ws/2/recording?query=recording:"<title>" AND artist:"<artist>"
 *                            AND dur:[<durationMs-10000> TO <durationMs+10000>]&fmt=json&limit=100
 * GET /ws/2/release-group?query=rgid:(<id> OR <id> OR …)&fmt=json&limit=100
 * ```
 *
 * `durationMs` is the real track duration, which is what makes the `dur:` bound reproducible.
 *
 * **Trimmed, not verbatim.** A capture runs to 200-600 candidates per track, which is
 * unreadable and undiffable. Each entry keeps one representative candidate per release group
 * the top rung accepts, plus up to five excluded candidates chosen to cover distinct exclusion
 * reasons (a Live or Compilation secondary type, a Promotion / Bootleg / Withdrawn status, an
 * undated release group). Nothing was hand-written or invented. The trimming was verified not
 * to change any answer: for all twenty-two tracks, the tier ladder returns the same year over
 * the trimmed set as over the full capture.
 *
 * `poolSize` records how many recordings the duration-bounded search reported in total, as
 * evidence for the `dur:` bound's effect -- "Stairway to Heaven" is 842 candidates unbounded
 * and 31 bounded, and that difference is why it resolves correctly (docs/agent_findings.md,
 * 2026-08-04).
 */

import type { RecordingCandidate } from '../types';

export interface YearFixture {
  key: string;
  /** The title as Spotify presents it, already cleaned -- none of these carry a suffix. */
  title: string;
  /** The raw joined artist string, as the embed payload's track-level `subtitle` gives it. */
  artist: string;
  durationMs: number;
  /** Ground truth. Not "what the code returns". */
  expectedYear: number;
  /** Why this track is in the suite. */
  note: string;
  /** Total recordings the duration-bounded search matched, before trimming. */
  poolSize: number;
  candidates: RecordingCandidate[];
}

/**
 * A track whose ground-truth year the pipeline provably CANNOT reach, with the year it
 * actually returns pinned so the limitation stays visible.
 *
 * ===========================================================================
 *  THIS IS NOT A FIXTURE WAITING TO BE FIXED BY BETTER FILTERING.
 *
 *  Year resolution is RECORDING-scoped: the adapter finds recordings, then asks
 *  which release groups those recordings appear on. That works whenever the
 *  single and the album share one master, which is the common case and the one
 *  the 2026-08-11 widening addresses.
 *
 *  It cannot work when the single is a DIFFERENT RECORDING. Measured
 *  2026-08-11: Depeche Mode's "Personal Jesus" is 4:55 on Violator, and the
 *  1989-08-29 single release group (which MusicBrainz has, dated correctly)
 *  carries a 3:46 edit -- a separate recording MBID that the album version
 *  never appears beside. The `dur:` bound is not what hides it; dropping the
 *  bound entirely still does not put the album recording on that single.
 *
 *  Reaching it needs WORK-level resolution (MusicBrainz `work` relationships
 *  group every recording of one song), which is a different and much larger
 *  change than a filter widening. Recorded rather than attempted.
 * ===========================================================================
 */
export interface LimitationFixture extends YearFixture {
  /** What the ladder returns today. Pinned so a change of behaviour is not silent. */
  resolvesTo: number;
}

